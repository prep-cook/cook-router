#!/usr/bin/env python3
"""Build the new boundary-codec harness from a clean checkout without modifying it."""
import datetime
import hashlib
import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys

BASELINE_REVISION = "b518060ea1e43ef4b266591986ca92321e6289b5"
# The S1 codecs are not yet declared in ck-translate's lib.rs, so the harness includes the
# same module files its integration tests include. Extension: list new protocol modules here.
CODEC_MODULES = {"codec": "crates/ck-translate/src/codec/mod.rs",
                 "boundary": "crates/ck-translate/src/boundary.rs",
                 "anthropic": "crates/ck-translate/src/anthropic/mod.rs",
                 "responses": "crates/ck-translate/src/responses/mod.rs",
                 "gemini": "crates/ck-translate/src/gemini/boundary.rs"}
INPUT_TREES = ("crates/ck-stream", "crates/ck-translate/src/codec", "crates/ck-translate/src/anthropic",
               "crates/ck-translate/src/responses", "crates/ck-translate/src/gemini")
HARNESS = ("bench/codec/new/harness.rs", "bench/codec/new/ops.rs", "bench/codec/new/protocols.rs",
           "bench/codec/new_launcher.py", "bench/codec/baseline_launcher.py", "bench/codec/build_new.py")


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def git(source, *args):
    return subprocess.check_output(["git", "-C", str(source), *args], text=True).strip()


def inputs(source):
    files = [source / "Cargo.toml", source / "Cargo.lock", source / "crates/ck-translate/src/boundary.rs"]
    for directory in INPUT_TREES:
        files.extend(p for p in sorted((source / directory).rglob("*")) if p.is_file())
    files.extend(source / name for name in HARNESS)
    relative = [str(p.relative_to(source)) for p in files]
    # The revision names the measured code only when no input differs from it.
    dirty = git(source, "status", "--porcelain", "--untracked-files=all", "--", *relative)
    if dirty:
        raise ValueError(f"commit or remove these harness inputs first:\n{dirty}")
    return {name: sha(source / name) for name in relative}


def pool_directory():
    path = Path(os.environ.get("CODEC_POOL_DIRECTORY") or "/scratch/ram/codecbench-pool")
    if not path.is_absolute():
        raise ValueError("CODEC_POOL_DIRECTORY must be absolute")
    path.mkdir(mode=0o700, exist_ok=True)
    fstype = subprocess.check_output(["findmnt", "-n", "-o", "FSTYPE", "--target", str(path)], text=True).strip()
    if fstype != "tmpfs":
        raise ValueError(f"pool directory {path} is on {fstype}, not tmpfs")
    return path


def crate(source, out):
    crate = out / "crate"
    (crate / "src").mkdir(parents=True)
    for name in HARNESS[:3]:
        shutil.copy2(source / name, crate / "src" / Path(name).name)
    main = "//! Generated by bench/codec/build_new.py.\n"
    for module, path in CODEC_MODULES.items():
        main += (f'#[allow(dead_code, unused_imports)]\n#[path = {json.dumps(str(source / path))}]\n'
                 f'pub mod {module};\n')
    main += "mod harness;\nmod ops;\nmod protocols;\n\nfn main() -> harness::Result<()> {\n    harness::main()\n}\n"
    (crate / "src/main.rs").write_text(main)
    shutil.copy2(source / "Cargo.lock", crate / "Cargo.lock")
    stream = json.dumps(str(source / "crates/ck-stream"))
    (crate / "Cargo.toml").write_text(
        '[package]\nname = "new-codec-harness"\nversion = "0.1.0"\nedition = "2024"\n\n[workspace]\n\n'
        f'[dependencies]\nck-stream = {{ path = {stream}, features = ["bench-hooks"] }}\n'
        'base64 = "0.22"\nserde_json = { version = "1", features = ["preserve_order"] }\n'
        'libc = "0.2"\nsha2 = "0.10"\n'
        '\n[profile.release]\nlto = "thin"\ncodegen-units = 1\nstrip = true\n')
    return crate


def build(crate, out):
    env = {**os.environ,
           "BUILD_CPUS": os.environ.get("BUILD_CPUS") or "8-15,24-31",
           "CARGO_BUILD_JOBS": os.environ.get("CARGO_BUILD_JOBS") or "4",
           "CARGO_TARGET_DIR": os.environ.get("CARGO_TARGET_DIR") or "/scratch/ssd/codecbench-target"}
    manifest = str(crate / "Cargo.toml")
    for args, log in ((["metadata", "--offline", "--format-version", "1"], "metadata.log"),
                      (["build", "--offline", "--locked", "--release"], "build.log")):
        with (out / log).open("w") as stream:
            subprocess.run(["taskset", "-c", env["BUILD_CPUS"], "cargo", *args, "--manifest-path", manifest],
                           env=env, stdout=stream, stderr=subprocess.STDOUT, check=True)
    shutil.copy2(Path(env["CARGO_TARGET_DIR"]) / "release/new-codec-harness", out / "new-codec-harness")
    return env


def main():
    if len(sys.argv) != 3:
        raise ValueError("usage: build-new.sh SOURCE OUT")
    source, out = (Path(arg).resolve() for arg in sys.argv[1:])
    revision = git(source, "rev-parse", "HEAD")
    if revision == BASELINE_REVISION:
        raise ValueError("the new harness cannot be built from the baseline revision")
    if source == out or source in out.parents:
        raise ValueError("OUT must be external to the source checkout")
    out.mkdir(parents=True, exist_ok=True)
    if any(out.iterdir()):
        raise ValueError("OUT must be empty")
    checksums = inputs(source)
    source_checksum = hashlib.sha256(json.dumps(checksums, sort_keys=True).encode()).hexdigest()
    (out / "source-checksums.json").write_text(json.dumps(checksums, indent=2) + "\n")
    pool = pool_directory()
    start = datetime.datetime.now(datetime.timezone.utc).isoformat()
    env = build(crate(source, out), out)
    for name in ("new_launcher.py", "baseline_launcher.py"):
        shutil.copy2(source / "bench/codec" / name, out / name)
    rustc = env.get("RUSTC", "rustc")
    provenance = {"schema_version": 1, "revision": revision, "source_checksum": source_checksum,
        "compiler": subprocess.check_output([rustc, "-Vv"], text=True).strip(),
        "target": subprocess.check_output([rustc, "-vV"], text=True).split("host: ")[1].splitlines()[0],
        "profile": "release", "features": ["ck-stream/bench-hooks"],
        "build_flags": ["--offline", "--locked", "--release", "lto=thin", "codegen-units=1", "strip=true"],
        "config": {"retention": "release-at-completion", "workers": 1, "allocator": "System",
                   "instrumentation": "global-alloc+process-cpu+monotonic+smaps+private-cgroup-v2"},
        "backend_config": {"implementation": "s1-boundary-codecs", "protocols": ["openai", "claude"],
                           "pool": "ck-stream Config::new defaults, workers=1, one store per process",
                           "pool_directory": str(pool), "release": "Writer::finish(Gone) per operation"},
        "build_environment": {key: env.get(key) for key in (
            "BUILD_CPUS", "CARGO_TARGET_DIR", "CARGO_BUILD_JOBS", "RUSTFLAGS", "CARGO_ENCODED_RUSTFLAGS",
            "RUSTC", "RUSTC_WRAPPER", "CARGO_PROFILE_RELEASE_LTO", "CARGO_PROFILE_RELEASE_CODEGEN_UNITS",
            "CARGO_PROFILE_RELEASE_OPT_LEVEL", "CARGO_PROFILE_RELEASE_STRIP", "CARGO_PROFILE_RELEASE_DEBUG",
            "CC", "CXX", "CFLAGS", "CXXFLAGS", "LDFLAGS")},
        "storage_directory": str(pool), "source_lock_sha256": sha(source / "Cargo.lock"),
        "resolved_lock_sha256": sha(out / "crate/Cargo.lock"),
        "build_start": start, "build_end": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "build_affinity": env["BUILD_CPUS"], "build_jobs": int(env["CARGO_BUILD_JOBS"]),
        "binary_sha256": sha(out / "new-codec-harness")}
    (out / "provenance.json").write_text(json.dumps(provenance, indent=2) + "\n")
    wrapper = out / "new-harness"
    wrapper.write_text('#!/usr/bin/env bash\nset -euo pipefail\nexport CODEC_NEW_PROVENANCE='
                       + shlex.quote(str(out / "provenance.json")) + '\nexec python3 -I -B '
                       + shlex.quote(str(out / "new_launcher.py")) + ' "$@"\n')
    wrapper.chmod(0o700)
    print(wrapper)


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print(f"new harness build: {error}", file=sys.stderr)
        sys.exit(2)
